#!/usr/bin/env node
/**
 * Generates the typed R|Protocol codec used by the Rithmic adapter.
 *
 *   npm run gen:rithmic
 *
 * Browsers cannot load .proto files at runtime the way the Node samples do, so
 * the messages the adapter uses are compiled ahead of time with protobufjs-cli
 * into a static ES module (src/rithmic/generated/rti.js) plus its
 * TypeScript declarations (rti.d.ts). Both are committed; rerun this script
 * after updating src/rithmic/proto/ or adding a message to PROTOS.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const protoDir = path.join(root, "src/rithmic/proto");
const outDir = path.join(root, "src/rithmic/generated");

/** Only what the adapter uses: keeps the lazily loaded Rithmic chunk small. */
const PROTOS = [
  // shared
  "message_type",
  "request_login",
  "response_login",
  "request_logout",
  "response_logout",
  "request_heartbeat",
  "response_heartbeat",
  "request_rithmic_system_info",
  "response_rithmic_system_info",
  "request_reference_data",
  "response_reference_data",
  "reject",
  "forced_logout",
  // ticker plant
  "request_market_data_update",
  "response_market_data_update",
  "request_front_month_contract",
  "response_front_month_contract",
  "request_search_symbols",
  "response_search_symbols",
  "last_trade",
  "best_bid_offer",
  "order_book",
  // history plant
  "request_time_bar_replay",
  "response_time_bar_replay",
  "request_resume_bars",
  "response_resume_bars",
  // order plant
  "request_login_info",
  "response_login_info",
  "request_account_list",
  "response_account_list",
  "request_trade_routes",
  "response_trade_routes",
  "request_subscribe_for_order_updates",
  "response_subscribe_for_order_updates",
  "request_new_order",
  "response_new_order",
  "request_modify_order",
  "response_modify_order",
  "request_cancel_order",
  "response_cancel_order",
  "request_cancel_all_orders",
  "response_cancel_all_orders",
  "request_show_orders",
  "response_show_orders",
  "request_bracket_order",
  "response_bracket_order",
  "request_update_target_bracket_level",
  "response_update_target_bracket_level",
  "request_update_stop_bracket_level",
  "response_update_stop_bracket_level",
  "request_subscribe_to_bracket_updates",
  "response_subscribe_to_bracket_updates",
  "request_show_brackets",
  "response_show_brackets",
  "request_exit_position",
  "response_exit_position",
  "rithmic_order_notification",
  "exchange_order_notification",
  "bracket_updates",
  // pnl plant
  "request_pnl_position_updates",
  "response_pnl_position_updates",
  "request_pnl_position_snapshot",
  "response_pnl_position_snapshot",
  "instrument_pnl_position_update",
  "account_pnl_position_update",
];

const require = createRequire(import.meta.url);
const cliDir = path.dirname(require.resolve("protobufjs-cli/package.json"));
const pbjs = path.join(cliDir, "bin/pbjs");
const pbts = path.join(cliDir, "bin/pbts");

mkdirSync(outDir, { recursive: true });
const jsOut = path.join(outDir, "rti.js");
const dtsOut = path.join(outDir, "rti.d.ts");
const tmpDir = mkdtempSync(path.join(os.tmpdir(), "gen-rithmic-"));
const commentedJs = path.join(tmpDir, "rti.js");

const pbjsArgs = (out, extra) => [
  pbjs,
  "-t", "static-module",
  "-w", "es6",
  "--force-number",
  "--no-verify",
  "--no-convert",
  "--no-delimited",
  "--no-service",
  ...extra,
  "-o", out,
  ...PROTOS.map((p) => path.join(protoDir, `${p}.proto`)),
];

try {
  // pbts derives the declarations from the JSDoc, so it needs the commented
  // build; the committed module is the comment-free one.
  execFileSync(process.execPath, pbjsArgs(commentedJs, []), { stdio: "inherit" });
  execFileSync(process.execPath, [pbts, "-o", dtsOut, commentedJs], { stdio: "inherit" });
  execFileSync(process.execPath, pbjsArgs(jsOut, ["--no-comments"]), { stdio: "inherit" });
} finally {
  rmSync(tmpDir, { recursive: true, force: true });
}

// protobufjs/minimal is CommonJS; the default import is the interop-safe form
// for both Vite (browser) and Vitest (Node).
const js = readFileSync(jsOut, "utf8").replace(
  'import * as $protobuf from "protobufjs/minimal";',
  'import $protobuf from "protobufjs/minimal.js";',
);
writeFileSync(jsOut, `// @ts-nocheck\n// Generated by scripts/gen-rithmic.mjs — do not edit.\n${js}`);
const dts = readFileSync(dtsOut, "utf8");
writeFileSync(dtsOut, `// Generated by scripts/gen-rithmic.mjs — do not edit.\n${dts}`);

console.log(`[gen:rithmic] ${PROTOS.length} protos → ${path.relative(root, jsOut)}, ${path.relative(root, dtsOut)}`);
